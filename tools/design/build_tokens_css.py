#!/usr/bin/env python3
"""Generate farglow/web/static/ds/tokens.css from tokens.json.

Usage:
    python3 tools/design/build_tokens_css.py          # write tokens.css
    python3 tools/design/build_tokens_css.py --check  # exit 1 if tokens.css is stale (test.sh)

tokens.json is the source of truth (design pack). Light theme is the :root default;
[data-theme="dark"] overrides the themed colours and shadows.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
DS = ROOT / "farglow" / "web" / "static" / "ds"
SRC = DS / "tokens.json"
OUT = DS / "tokens.css"


def build(tokens: dict) -> str:
    light, dark, common = [], [], []
    for t in tokens["color"]["tokens"]:
        v = t["value"]
        if isinstance(v, str):  # alias, e.g. "{accent}"
            ref = v.strip("{}")
            light.append(f"  --{t['name']}: var(--{ref});")
            continue
        light.append(f"  --{t['name']}: {v['light']};")
        if v["dark"] != v["light"]:
            dark.append(f"  --{t['name']}: {v['dark']};")
    for t in tokens["shadow"]["tokens"]:
        light.append(f"  --{t['name']}: {t['value']['light']};")
        dark.append(f"  --{t['name']}: {t['value']['dark']};")
    fam = tokens["type"]["families"]
    common.append(f"  --font-sans: {fam['sans']};")
    common.append(f"  --font-mono: {fam['mono']};")
    for group in ("spacing", "radius", "size"):
        for t in tokens[group]["tokens"]:
            common.append(f"  --{t['name']}: {t['value']};")
    styles = []
    for g in tokens["type"]["groups"]:
        for s in g["styles"]:
            styles.append(
                f".{s['name']} {{ font-family: var(--font-{g['family']}); font-size: {s['fontSize']}; "
                f"line-height: {s['lineHeight']}; font-weight: {s['fontWeight']};"
                + (f" letter-spacing: {s['letterSpacing']};" if s.get("letterSpacing") else "")
                + (" font-variant-numeric: tabular-nums;" if g["family"] == "mono" else "")
                + " }"
            )
    return (
        "/* GENERATED by tools/design/build_tokens_css.py from tokens.json. Do not edit. */\n"
        ":root {\n" + "\n".join(common + light) + "\n  color-scheme: light;\n}\n"
        '[data-theme="dark"] {\n' + "\n".join(dark) + "\n  color-scheme: dark;\n}\n"
        + "\n".join(styles) + "\n"
    )


def main() -> int:
    css = build(json.loads(SRC.read_text(encoding="utf-8")))
    if "--check" in sys.argv[1:]:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != css:
            print(f"{OUT.relative_to(ROOT)} is stale: run python3 tools/design/build_tokens_css.py")
            return 1
        return 0
    OUT.write_text(css, encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
